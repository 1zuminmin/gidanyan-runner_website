CREATE TABLE IF NOT EXISTS runs (player TEXT PRIMARY KEY, id TEXT NOT NULL UNIQUE, started INTEGER NOT NULL, submission TEXT);
CREATE TABLE IF NOT EXISTS scores (player TEXT PRIMARY KEY, nickname TEXT NOT NULL, score INTEGER NOT NULL, distance INTEGER NOT NULL, candy INTEGER NOT NULL, elapsed REAL NOT NULL, updated INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS scores_order ON scores(score DESC, updated ASC, player ASC);
CREATE TABLE IF NOT EXISTS score_buckets (bucket INTEGER PRIMARY KEY, n INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS ranking_stats (id INTEGER PRIMARY KEY CHECK(id=1), n INTEGER NOT NULL);
INSERT OR IGNORE INTO ranking_stats VALUES(1,0);
CREATE TRIGGER IF NOT EXISTS scores_insert AFTER INSERT ON scores BEGIN
 INSERT INTO score_buckets VALUES(CAST(NEW.score/10000 AS INTEGER),1) ON CONFLICT(bucket) DO UPDATE SET n=n+1;
 UPDATE ranking_stats SET n=n+1 WHERE id=1;
END;
CREATE TRIGGER IF NOT EXISTS scores_update AFTER UPDATE OF score ON scores WHEN CAST(OLD.score/10000 AS INTEGER) != CAST(NEW.score/10000 AS INTEGER) BEGIN
 UPDATE score_buckets SET n=n-1 WHERE bucket=CAST(OLD.score/10000 AS INTEGER);
 DELETE FROM score_buckets WHERE bucket=CAST(OLD.score/10000 AS INTEGER) AND n=0;
 INSERT INTO score_buckets VALUES(CAST(NEW.score/10000 AS INTEGER),1) ON CONFLICT(bucket) DO UPDATE SET n=n+1;
END;
CREATE TRIGGER IF NOT EXISTS scores_delete AFTER DELETE ON scores BEGIN
 UPDATE score_buckets SET n=n-1 WHERE bucket=CAST(OLD.score/10000 AS INTEGER);
 DELETE FROM score_buckets WHERE bucket=CAST(OLD.score/10000 AS INTEGER) AND n=0;
 UPDATE ranking_stats SET n=n-1 WHERE id=1;
END;
